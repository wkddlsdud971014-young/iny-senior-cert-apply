# =============================================================
# 조사·어미 떼기
#
# 한국어는 낱말 뒤에 조사가 붙습니다.
#   "접수비가"  →  "접수비"
#   "얼마예요"  →  "얼마"
# 이걸 안 떼면 "접수비가"와 "접수비"를 다른 낱말로 셉니다.
# =============================================================

PARTICLES = [
    # 어미
    "입니까", "인가요", "이에요", "예요", "인지", "나요", "까요", "군요", "네요",
    # 조사
    "이라고", "라고", "부터", "까지", "에서", "으로", "한테", "에게", "께서",
    "이랑", "하고", "보다", "처럼", "마다", "조차", "밖에", "이나", "거나",
    "은", "는", "이", "가", "을", "를", "의", "에", "로", "와", "과",
    "도", "만", "요", "랑", "께", "서",
]


def stem(word):
    """낱말 뒤에 붙은 조사·어미를 뗍니다. 너무 짧아지면 그대로 둡니다."""
    for p in sorted(PARTICLES, key=len, reverse=True):
        if len(word) > len(p) + 1 and word.endswith(p):
            return word[: -len(p)]
    return word

-- =============================================================
-- 문서에 섞인 "직원용 주의사항"을 어르신께 드리는 말로 바꿉니다.
--
-- 실행 위치: Supabase 대시보드 > SQL Editor > New query > 붙여넣고 Run
-- 실행 횟수: 여러 번 돌려도 됩니다. 이미 고쳐졌으면 아무 일도 안 일어납니다.
--
-- [무슨 일이 있었나]
--   배포된 챗봇에 "필기 합격은 몇 년 유효한가요?" 라고 물으면 이렇게 답했습니다.
--
--     국가기술자격 기능사는 필기 합격이 2년간 유효합니다.
--     자격증마다 다르므로 뭉뚱그려 2년이라고 답하면 안 됩니다.   ← 이 줄
--
--   뒷줄은 어르신께 드리는 말이 아닙니다. 발주 문서(02_안내규정.md 156줄)에
--   적힌 "우리끼리 보는 주의사항"입니다.
--
--     **뭉뚱그려 "2년"이라고 답하면 안 됩니다.** 자격증마다 다릅니다.
--
--   문서를 옮겨 적을 때 이 줄까지 같이 들어갔고, 챗봇이 그대로 읽었습니다.
--   어르신은 "나더러 답하지 말라는 건가" 하시게 됩니다.
--
-- [왜 그냥 지우지 않나]
--   그 줄이 담고 있는 사실 자체는 맞습니다. 공인중개사는 기간이 다릅니다.
--   지우기만 하면 "공인중개사도 2년" 으로 잘못 아시게 됩니다.
--   그래서 같은 사실을 어르신께 드리는 말로 바꿔 적습니다.
--
--   공인중개사 면제 기간은 발주처가 확인하지 못한 8가지 가운데 하나입니다.
--   (02_안내규정.md 154줄 — "공식 문서로 확인하지 못했습니다")
--   그러니 기간을 적지 않고 확인하지 못했다고 밝힙니다. 짐작해서 채우지 않습니다.
--
-- [문서를 옮겨 적으실 때]
--   발주 문서에는 두 가지가 섞여 있습니다.
--     어르신께 드릴 말   → 문서에 옮긴다
--     우리끼리 볼 주의사항 → 옮기지 않는다. 코드나 주석에 남긴다
--   옮기기 전에 "이 문장을 어르신이 읽으셔도 되는가" 를 한 번 보십시오.
--
--   같은 기준으로 문서 21건을 훑었고, 이 한 건만 걸렸습니다.
--   「응시료를 확인하지 못한 자격증」의 "짐작해서 알려드리지 않습니다" 는
--   어르신께 드리는 약속이라 그대로 둡니다.
-- =============================================================


update public.faq_docs
set content =
  '국가기술자격 기능사는 필기 합격이 2년간 유효합니다. '
  '2년 안에는 필기를 다시 보지 않으셔도 됩니다. '
  '2년이 지나면 필기부터 다시 보셔야 합니다. '
  '공인중개사는 기간이 다릅니다. '
  '공인중개사 면제 기간은 저희가 확인하지 못했으니 공식 사이트에서 확인해 주십시오.'
where title = '필기 합격의 유효기간'
  and content like '%답하면 안 됩니다%';


-- 확인 -------------------------------------------------------------

-- 아래 내용에 "답하면 안 됩니다" 가 없어야 합니다.
select title, content
from public.faq_docs
where title = '필기 합격의 유효기간';

-- 0 이 나와야 합니다. 직원용 주의사항이 남은 문서 수입니다.
select count(*) as 주의사항남은문서
from public.faq_docs
where content like '%답하면 안%' or content like '%안내하면 안%';

-- 실행 위치: Supabase 대시보드 > SQL Editor > New query > Run
-- 실행 횟수: 1회
--
-- [왜 표로 옮기나]
--   지금은 챗봇이 파일(chatbot/faq.json)을 읽습니다.
--   그러면 발주처 직원이 문서를 고칠 수 없습니다.
--     "저희가 문서를 직접 고칠 수 있는지가 중요합니다.
--      접수 기간은 자주 바뀝니다." (01_사업현황_발주서.md 117줄)
--   표로 옮기면 직원이 웹 화면에서 고치고, 챗봇이 바로 그 내용을 읽습니다.
--
-- [접수 데이터와 다른 점]
--   applications 는 원본이라 고칠 수 없게 막았습니다.
--   faq_docs 는 운영 문서라 고칠 수 있어야 정상입니다.
--   다만 지우기는 막고, 대신 '숨김'으로 내려 둡니다.
--   한 번 적은 문서를 실수로 없애지 않기 위해서입니다.
-- =============================================================


create table public.faq_docs (
  id          bigint generated always as identity primary key,

  sort_order  int  not null default 0,      -- 보여 주는 차례
  title       text not null,                -- 문서 제목
  content     text not null,                -- 문서 내용

  is_active   boolean     not null default true,   -- 끄면 챗봇이 안 읽습니다
  updated_at  timestamptz not null default now(),  -- 마지막으로 고친 때
  created_at  timestamptz not null default now()
);

comment on table public.faq_docs is '챗봇이 읽는 문서. 직원이 웹 화면에서 고칩니다.';

create index faq_docs_active_idx on public.faq_docs (is_active, sort_order);


-- 접근 권한 -----------------------------------------------------

alter table public.faq_docs enable row level security;

create policy "문서 읽기"   on public.faq_docs for select to anon using (true);
create policy "문서 고치기" on public.faq_docs for update to anon using (true) with check (true);
create policy "문서 새로 넣기" on public.faq_docs for insert to anon with check (true);

-- delete 정책은 만들지 않습니다.
-- 지우는 대신 is_active 를 false 로 내려 두면 챗봇이 읽지 않습니다.
-- 실수로 문서를 없애는 일을 막기 위해서입니다.


-- 고친 때를 자동으로 기록 ---------------------------------------

create or replace function public.faq_docs_touch()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger faq_docs_touch_trg
  before update on public.faq_docs
  for each row execute function public.faq_docs_touch();



-- =============================================================
-- 안내문 4건 추가 — 챗봇 답변 단계를 셋으로 나누면서 필요해진 문구입니다.
--
-- 실행 위치: Supabase 대시보드 > SQL Editor > New query > 붙여넣고 Run
-- 실행 횟수: 여러 번 돌려도 됩니다. 이미 있는 제목은 건너뜁니다.
--
-- [왜 필요한가]
--   챗봇이 답을 세 단계로 나눕니다. (starter/api/chat.js)
--     답변 가능       근거가 있다            → 근거대로 답한다
--     조건부 답변 가능  그건 못 하지만 이건 된다 → 못 하는 것 + 되는 것을 같이 말한다
--     답변 불가       저희 범위 밖이다        → 안 된다고만 말한다
--
--   가운데 "조건부"에서 할 말이 새로 필요합니다.
--   전에는 이런 질문을 전부 "모르겠습니다"로 끊었습니다.
--     "제가 합격할 수 있을까요?"      → 모르겠습니다
--     "시험장에 주차 되나요?"         → 모르겠습니다
--     "요양보호사 응시료 얼마예요?"    → 모르겠습니다
--   합격 여부는 정말 알 수 없습니다. 그런데 시험 일정과 준비물은 저희가 압니다.
--   어르신은 "여기서는 아무것도 안 알려주는구나" 하고 끊으셨습니다.
--
-- [왜 코드가 아니라 표에 넣나]
--   "언제 끊을지"는 코드가 정합니다. 직원이 바꾸면 안 되는 원칙이라서입니다.
--   "뭐라고 말할지"는 직원이 어드민 화면에서 고칠 수 있어야 합니다.
--   거절 문구(안내문 · 모를 때 / 실기 질문)를 표에 둔 것과 같은 이유입니다.
--
-- [문구를 고치실 때]
--   제목은 바꾸지 마십시오. 코드가 제목으로 문서를 찾습니다.
--   내용만 고치시면 됩니다. 표를 못 읽어도 코드에 적힌 기본 문구로 돕니다.
--
--   "확인 못 한 항목"은 앞에 한 줄이 자동으로 붙습니다.
--     예) "요양보호사 응시료는 저희가 확인하지 못했습니다."
--   그래서 이 문서에는 어느 항목에나 통하는 말만 적습니다.
--
-- [지어내지 않는다는 원칙]
--   조건부도 없는 사실을 만들지 않습니다.
--   못 하는 것은 여전히 못 한다고 말하고, 할 수 있는 일을 덧붙일 뿐입니다.
-- =============================================================


-- 900번대는 안내문 자리입니다. 챗봇이 근거 문서로 쓰지 않고 답변 문구로만 씁니다.
--   900 안내문 · 모를 때        (이미 있음)
--   910 안내문 · 실기 질문       (이미 있음 · 아래에서 조건부 말투로 고칩니다)
--   920 안내문 · 확인 못 한 항목  ← 새로 넣음
--   930 안내문 · 합격 예측       ← 새로 넣음
--   940 안내문 · 시험장 시설      ← 새로 넣음
--   950 안내문 · 여러 자격증      ← 새로 넣음

insert into public.faq_docs (sort_order, title, content)
select v.sort_order, v.title, v.content
from (values
  (920, '안내문 · 확인 못 한 항목',
   E'짐작해서 말씀드리면 잘못 안내될 수 있어 알려드리지 않습니다.\n대신 어디서 접수하는지, 언제까지 접수하는지는 알려드릴 수 있습니다.'),

  (930, '안내문 · 합격 예측',
   E'합격 여부를 미리 판단해 드릴 수는 없습니다.\n대신 시험 일정이나 시험 당일 준비물은 알려드릴 수 있습니다.'),

  (940, '안내문 · 시험장 시설',
   E'시험장 안의 시설은 저희가 확인하지 못했습니다.\n시험장을 어디서 고르는지, 무엇을 가져가시는지는 알려드릴 수 있습니다.'),

  (950, '안내문 · 여러 자격증',
   E'여러 자격증을 함께 준비하시는 것이 좋을지는 저희가 판단해 드릴 수 없습니다.\n저희가 다루는 여덟 가지 가운데 궁금한 자격증의 접수 방법은 알려드릴 수 있습니다.')
) as v(sort_order, title, content)
where not exists (
  select 1 from public.faq_docs d where d.title = v.title
);


-- 실기 질문 안내문을 조건부 말투로 바꿉니다.
--
-- 전:  저희는 필기 접수만 도와드립니다. 실기는 저희가 안내하지 않습니다.
-- 후:  실기는 저희가 안내해 드리지 않습니다.
--      필기 접수는 저희가 도와드립니다. 필기에 대해 물어봐 주십시오.
--
-- 안 된다는 말로 끝내지 않고, 그다음에 무엇을 하시면 되는지까지 말씀드립니다.
-- 직원이 이미 손으로 고쳐 두셨을 수 있어, 원래 문구일 때만 바꿉니다.

update public.faq_docs
set content = E'실기는 저희가 안내해 드리지 않습니다.\n필기 접수는 저희가 도와드립니다. 필기에 대해 물어봐 주십시오.'
where title = '안내문 · 실기 질문'
  and content like '%필기 접수만 도와드립니다%';


-- 확인 -------------------------------------------------------------

select sort_order, title, content
from public.faq_docs
where title like '안내문%'
order by sort_order;

-- 안내문은 6건이어야 합니다 (900 910 920 930 940 950)
select count(*) as 안내문수 from public.faq_docs where title like '안내문%';


